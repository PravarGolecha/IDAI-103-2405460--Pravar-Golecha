import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split, cross_val_score, GridSearchCV
from sklearn.ensemble import RandomForestClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import accuracy_score, classification_report
from sklearn.feature_selection import RFE

# 1. Simulate a dataset (replace with your own dataset)
# For illustration, we're using the famous Iris dataset here.
from sklearn.datasets import load_iris
data = load_iris()
X = data.data
y = data.target

# 2. Data Preprocessing: Scaling (if required by your model)
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# 3. Split the dataset into training and testing sets (80% train, 20% test)
X_train, X_test, y_train, y_test = train_test_split(X_scaled, y, test_size=0.2, random_state=42)

# 4. Train a Random Forest Classifier (initial model)
model = RandomForestClassifier(random_state=42)

# 5. Model Validation: Cross-validation (5-fold)
cv_scores = cross_val_score(model, X_train, y_train, cv=5)
print(f"Cross-validation scores: {cv_scores}")
print(f"Mean cross-validation score: {cv_scores.mean()}")

# 6. Hyperparameter Tuning: GridSearchCV to find the best hyperparameters
param_grid = {
    'n_estimators': [100, 200],
    'max_depth': [10, 20, 30],
    'min_samples_split': [2, 5]
}

grid_search = GridSearchCV(model, param_grid, cv=5)
grid_search.fit(X_train, y_train)

# Best parameters found from GridSearchCV
print(f"Best parameters from grid search: {grid_search.best_params_}")

# 7. Feature Selection (Optional): RFE (Recursive Feature Elimination)
selector = RFE(grid_search.best_estimator_, n_features_to_select=2)
X_train_selected = selector.fit_transform(X_train, y_train)
X_test_selected = selector.transform(X_test)

# 8. Retrain model with the best parameters and selected features
best_model = grid_search.best_estimator_

# Train the model on selected features
best_model.fit(X_train_selected, y_train)

# 9. Evaluate the Model: Test accuracy
y_pred = best_model.predict(X_test_selected)
accuracy = accuracy_score(y_test, y_pred)
print(f"Test accuracy: {accuracy}")

# 10. Evaluate model performance: Classification report
print("Classification Report:\n", classification_report(y_test, y_pred))

